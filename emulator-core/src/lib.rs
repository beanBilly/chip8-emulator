const fontSetSize: usize = 80;

const fontSet: [u8;fontSetSize] = [
    0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
    0x20, 0x60, 0x20, 0x20, 0x70, // 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
    0x90, 0x90, 0xF0, 0x10, 0x10, // 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
    0xF0, 0x10, 0x20, 0x40, 0x40, // 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
    0xF0, 0x90, 0xF0, 0x90, 0x90, // A
    0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
    0xF0, 0x80, 0x80, 0x80, 0xF0, // C
    0xE0, 0x90, 0x90, 0x90, 0xE0, // D
    0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
    0xF0, 0x80, 0xF0, 0x80, 0x80  // F
];

pub struct chip8{
	pub ram: [u8;4096],
	pub generalPurposeRegister: [u8;16],
	pub addressIndexRegister: u16,
	pub programCounter: u16,
	pub stack: [u16;16],
	pub stackPoint: u8,
	pub delayTimer: u8,
	pub soundTimer: u8,
	pub display: [u8;256],
	pub key: [bool;16]	
}

impl chip8{
	pub fn new()->Self{
		let mut newRam= [0;4096];
		
		for i in 0..fontSetSize{
			newRam[i]=fontSet[i];
		}
		
		Self{
			ram: newRam,
			generalPurposeRegister: [0;16],
			addressIndexRegister: 0,
			programCounter: 0x200,
			stack: [0;16],
			stackPoint: 0,
			delayTimer: 0,
			soundTimer: 0,
			display: [0;256],
			key: [false;16]	
		}
	}
}
